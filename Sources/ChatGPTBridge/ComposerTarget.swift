import Foundation

/// 一段文字该打进哪个输入框。
///
/// **存在的理由是一个真机缺陷（2026-08-08）：** 此前 `sendText` 只会「找一个输入框」，
/// 而语音起来之后，普通聊天的输入框仍然在无障碍树里、往往还排在语音框前面。
/// 于是考官提示词被打进了那个属于文字会话的框——用户看到的是
/// 「新建对话 → 点语音 → 又冒出一个文字对话，提示词进了那里」，
/// 而语音那边一个字都没收到，整场练习变成对着一个什么都不知道的聊天机器人说话。
///
/// 单元测试全绿也照样发生：假 Bridge 里只有一个框子，永远选不错。
public enum ComposerTarget: Equatable, Sendable {
    /// 语音会话的输入框（description 为 `Work with ChatGPT`）。
    ///
    /// **发考官提示词必须用这个。** 实测语音启动后第 9~11 秒有个窗口：
    /// `Voice chat active` 已经出现，但输入框描述仍是普通聊天态的 `Message ChatGPT`，
    /// 约 3 秒后才变成语音态。这一档会一直等到语音框真的出现为止。
    case voice
    /// 界面上任意一个输入框。
    ///
    /// 只在**确定当前不在语音会话里**时用——例如结束语音之后发复盘请求。
    case any
}
